using System.Text.Json;
using System.Text.Json.Serialization;

namespace VanPattenAIRouter.Models;

/// <summary>
///     Represents a chat message in the conversation.
/// </summary>
public class ChatMessage
{
    /// <summary>
    ///     The role of the messages author. One of system, user, assistant, or tool.
    /// </summary>
    public string Role { get; set; } = "";

    /// <summary>
    ///     The contents of the message. Can be a string for text-only messages or an array for multimodal content (text +
    ///     images).
    /// </summary>
    public object? Content { get; set; } = "";

    /// <summary>
    ///     The name of the author of this message. Required if role is "tool", otherwise optional.
    /// </summary>
    public string? Name { get; set; }

    /// <summary>
    ///     The tool calls generated by the model, such as function calls.
    /// </summary>
    public List<ChatToolCall>? ToolCalls { get; set; }

    /// <summary>
    ///     Tool call that this message is responding to.
    /// </summary>
    public string? ToolCallId { get; set; }

    /// <summary>
    ///     The refusal message generated by the model.
    /// </summary>
    [JsonPropertyName("refusal")]
    public string? Refusal { get; set; }

    /// <summary>
    ///     Audio data returned by the model (for audio modalities).
    /// </summary>
    [JsonPropertyName("audio")]
    public ChatAudio? Audio { get; set; }

    /// <summary>
    ///     Annotations for the message (e.g., URL citations from web search).
    /// </summary>
    [JsonPropertyName("annotations")]
    public List<ChatAnnotation>? Annotations { get; set; }

    /// <summary>
    ///     Gets the text content of the message, extracting text from multimodal content arrays if present.
    /// </summary>
    /// <returns>The text content as a string, or empty string if no text content.</returns>
    public string GetTextContent()
    {
        if (Content == null) return "";
        if (Content is string s) return s;
        if (Content is JsonElement el)
        {
            if (el.ValueKind == JsonValueKind.String) return el.GetString() ?? "";
            if (el.ValueKind == JsonValueKind.Array)
            {
                // Extract text from multimodal content array
                var texts = new List<string>();
                foreach (var item in el.EnumerateArray())
                    if (item.TryGetProperty("type", out var typeProp) &&
                        typeProp.GetString() == "text" &&
                        item.TryGetProperty("text", out var textProp))
                        texts.Add(textProp.GetString() ?? "");

                return string.Join(" ", texts);
            }

            return Content.ToString() ?? "";
        }

        return Content.ToString() ?? "";
    }
}