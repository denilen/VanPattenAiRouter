namespace VanPattenAIRouter.Models;

/// <summary>
///     Represents a chat completion response compatible with OpenAI API format.
/// </summary>
public class ChatCompletionResponse
{
    /// <summary>
    ///     A unique identifier for the chat completion.
    /// </summary>
    public string Id { get; set; } = Guid.NewGuid().ToString();

    /// <summary>
    ///     The object type, which is always "chat.completion".
    /// </summary>
    public string Object { get; set; } = "chat.completion";

    /// <summary>
    ///     The Unix timestamp (in seconds) of when the chat completion was created.
    /// </summary>
    public long Created { get; set; } = DateTimeOffset.UtcNow.ToUnixTimeSeconds();

    /// <summary>
    ///     The model used for the chat completion.
    /// </summary>
    public string Model { get; set; } = "";

    /// <summary>
    ///     A list of chat completion choices. Can be more than one if n is greater than 1.
    /// </summary>
    public List<ChatChoice> Choices { get; set; } = new();

    /// <summary>
    ///     Usage statistics for the completion request.
    /// </summary>
    public Usage Usage { get; set; } = new();

    /// <summary>
    ///     This fingerprint represents the backend configuration that the model runs with.
    /// </summary>
    public string? SystemFingerprint { get; set; }
}

/// <summary>
///     Represents a single choice in a chat completion response.
/// </summary>
public class ChatChoice
{
    /// <summary>
    ///     The index of the choice in the list of choices.
    /// </summary>
    public int Index { get; set; }

    /// <summary>
    ///     The message generated by the model.
    /// </summary>
    public ChatMessage Message { get; set; } = new();

    /// <summary>
    ///     The reason the model stopped generating tokens. Can be "stop", "length", "tool_calls", "content_filter", or
    ///     "function_call".
    /// </summary>
    public string FinishReason { get; set; } = "stop";
}

/// <summary>
///     Represents token usage statistics for a request.
/// </summary>
public class Usage
{
    /// <summary>
    ///     Number of tokens in the prompt.
    /// </summary>
    public int PromptTokens { get; set; }

    /// <summary>
    ///     Number of tokens in the generated completion.
    /// </summary>
    public int CompletionTokens { get; set; }

    /// <summary>
    ///     Total number of tokens used in the request (prompt + completion).
    /// </summary>
    public int TotalTokens { get; set; }
}